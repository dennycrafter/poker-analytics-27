// Generates tests/fixtures/money-golden.json by RUNNING the web app's own
// money modules (js/bankroll.js, js/staking.js, js/rankings.js, js/stats.js,
// js/manage.js) in Node on the shared input grid from tests/money-cases.ts.
// The native parity test replays the stored inputs through the TS ports and
// requires identical output.
//
// Run: npm run gen:money-golden   (re-run whenever the web formulas change)

import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import * as WB from '../../js/bankroll.js';
import { fmtNum } from '../../js/format.js';
import * as WMG from '../../js/manage.js';
import * as WR from '../../js/rankings.js';
import { buildSeed } from '../../js/seed.js';
import * as WS from '../../js/stats.js';
import * as WK from '../../js/staking.js';

import { blankDoc, type Doc } from '../src/lib/types';
import { buildInputs, computeMoney, NOW, type MoneyApi } from '../tests/money-cases';

// The web modules are untyped JS; the recipe's MoneyApi is the contract.
const webApi: MoneyApi = {
  endedSessions: WS.endedSessions,
  cashOnly: WS.cashOnly,
  riskOfRuin: WS.riskOfRuin,
  txnSigned: WB.txnSigned,
  signedAmount: WB.signedAmount,
  transactionError: WB.transactionError,
  bankrollSummary: (doc, id) => WB.bankrollSummary(doc, id as null),
  bankrollSeries: (doc, id) => WB.bankrollSeries(doc, id as null),
  bankrollUsage: WB.bankrollUsage,
  // JS default `exceptId = null` makes TS infer `null`; the web code takes any id.
  bankrollNameError: (doc, name, exceptId) => WMG.masterNameError(doc, 'bankrolls', name, exceptId as null),
  bankrollDeleteError: (doc, id) => WMG.masterDeleteError(doc, 'bankrolls', id),
  rorBandClass: WB.rorBand,
  soldPercent: WK.soldPercent,
  sellActionError: WK.sellActionError,
  makeSellAction: WK.makeSellAction,
  // Web keeps sellSummary in js/screens/sell.js (DOM module); this is its body verbatim.
  sellSummary: actions => { const p = WK.soldPercent(actions); return p > 0 ? `${fmtNum(p)}% sold` : 'None'; },
  sellActionsOf: WK.sellActionsOf,
  sellLedger: WK.sellLedger,
  topSessions: WR.topSessions,
};

const seed: Doc = { ...blankDoc(), ...(buildSeed(NOW) as unknown as Partial<Doc>), extra_master: {} };
const inputs = buildInputs(seed);
// Freeze the inputs exactly as JSON would carry them, then compute on that copy.
const frozen = JSON.parse(JSON.stringify(inputs)) as typeof inputs;
const expected = computeMoney(webApi, frozen);

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, '..', 'tests', 'fixtures', 'money-golden.json');
mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, JSON.stringify({
  note: 'GENERATED by scripts/gen-money-golden.ts from the web modules. Do not edit by hand.',
  inputs: frozen,
  expected,
}, null, 1) + '\n');
console.log(`wrote ${out}`);
